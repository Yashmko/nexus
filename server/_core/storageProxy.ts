import type { Express, Request, Response } from "express";
import { getMission } from "../db";
import { ENV } from "./env";
import { sdk } from "./sdk";

/**
 * Mission evidence keys are written by `server/storage.ts` as
 * `missions/<missionId>/<kind>/<fileName>_<hash>`. Evidence bytes are only ever
 * exposed through this proxy, so the proxy must apply the same owner/assignment
 * scoping as the tRPC procedures that list the attachments.
 */
const MISSION_KEY_PREFIX = "missions/";

/**
 * Rejects keys containing empty, `.` or `..` segments (or absolute prefixes).
 * Legitimate keys are generated by `storagePut`, which never produces those, and
 * rejecting them keeps the proxy from being used as a path-traversal pivot
 * against the object store.
 */
export function isWellFormedStorageKey(key: string): boolean {
  const normalized = key.replace(/^\/+/, "");
  if (!normalized || normalized.length > 1024) return false;
  return normalized.split("/").every((segment) => segment !== "" && segment !== "." && segment !== "..");
}

/**
 * Returns the mission id for a mission-scoped storage key, or `null` when the
 * key is not a well-formed mission object. `null` means "deny" for any
 * `missions/` key.
 */
export function parseMissionScopedKey(key: string): number | null {
  const normalized = key.replace(/^\/+/, "");
  const match = /^missions\/(\d+)\/(.+)$/.exec(normalized);
  if (!match) return null;
  const missionId = Number(match[1]);
  return Number.isSafeInteger(missionId) && missionId > 0 ? missionId : null;
}

export function registerStorageProxy(app: Express) {
  app.get("/manus-storage/*", async (req, res) => {
    const key = (req.params as Record<string, string>)[0];
    if (!key) {
      res.status(400).send("Missing storage key");
      return;
    }

    if (!isWellFormedStorageKey(key)) {
      res.status(400).send("Invalid storage key");
      return;
    }

    if (!ENV.forgeApiUrl || !ENV.forgeApiKey) {
      res.status(500).send("Storage proxy not configured");
      return;
    }

    // Mission-scoped objects are not public: authenticate the caller and verify
    // mission access (owner, assigned operator, or administrator) before minting
    // a presigned URL. Non-mission assets (the public product artwork) keep the
    // original behaviour.
    if (key.replace(/^\/+/, "").startsWith(MISSION_KEY_PREFIX)) {
      const authorized = await authorizeMissionObject(req, res, key);
      if (!authorized) return;
    }

    try {
      const forgeUrl = new URL(
        "v1/storage/presign/get",
        ENV.forgeApiUrl.replace(/\/+$/, "") + "/",
      );
      forgeUrl.searchParams.set("path", key);

      const forgeResp = await fetch(forgeUrl, {
        headers: { Authorization: `Bearer ${ENV.forgeApiKey}` },
      });

      if (!forgeResp.ok) {
        const body = await forgeResp.text().catch(() => "");
        console.error(`[StorageProxy] forge error: ${forgeResp.status} ${body}`);
        res.status(502).send("Storage backend error");
        return;
      }

      const { url } = (await forgeResp.json()) as { url: string };
      if (!url) {
        res.status(502).send("Empty signed URL from backend");
        return;
      }

      res.set("Cache-Control", "no-store");
      res.redirect(307, url);
    } catch (err) {
      console.error("[StorageProxy] failed:", err);
      res.status(502).send("Storage proxy error");
    }
  });
}

/**
 * Authorizes a `missions/...` storage request. Returns `true` when the request
 * may proceed; otherwise it has already written the response and returns `false`.
 * Failures are deliberately indistinguishable (404) so the endpoint cannot be
 * used to probe which mission ids or object keys exist.
 */
async function authorizeMissionObject(req: Request, res: Response, key: string): Promise<boolean> {
  const missionId = parseMissionScopedKey(key);
  if (missionId === null) {
    res.status(404).send("Storage object not found");
    return false;
  }

  let actor: Awaited<ReturnType<typeof sdk.authenticateRequest>>;
  try {
    // Accepts the session cookie or the Bearer fallback used when browsers block
    // iframe cookies.
    actor = await sdk.authenticateRequest(req);
  } catch {
    res.status(401).send("Authentication required");
    return false;
  }

  try {
    const mission = await getMission({ id: actor.id, role: actor.role }, missionId);
    if (!mission) {
      res.status(404).send("Storage object not found");
      return false;
    }
  } catch (error) {
    // Storage/database unavailability must fail closed rather than fall through
    // to an unauthenticated presign.
    console.error("[StorageProxy] authorization check failed:", error);
    res.status(503).send("Storage authorization unavailable");
    return false;
  }

  return true;
}
